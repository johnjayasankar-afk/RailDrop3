/* Rebuild supabase/SETUP_ALL.sql from the migrations.
 *
 *   node scripts/build-setup-sql.mjs
 *
 * A new Supabase project needs all nine migrations applied in order, and doing
 * that by hand in the SQL editor is nine chances to paste one out of order. This
 * concatenates them into one script that can be pasted once.
 *
 * The only edit it makes is to put `drop policy if exists` in front of every
 * `create policy`. The migrations do not do that themselves, and should not: a
 * migration runs once, against a database whose state is known. A setup script
 * gets re-run — after a half-finished attempt, or against a project someone
 * already poked at — and `create policy` is the one statement in here with no
 * `if not exists` form, so without this the second run fails on a policy that
 * already exists and leaves the rest unapplied.
 *
 * Run this after adding a migration, or SETUP_ALL.sql will be missing it.
 * tests/unit/setup-sql.test.ts fails if they have drifted apart.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import path from "node:path";

const MIGRATIONS = "supabase/migrations";
const OUT = "supabase/SETUP_ALL.sql";

const HEADER = `-- RailDrop database — complete schema, in one script.
--
-- Paste the whole file into a new Supabase project's SQL editor and run it once.
-- It replaces running the nine files in supabase/migrations/ by hand, and it is
-- the same SQL in the same order, generated by scripts/build-setup-sql.mjs.
--
-- Safe to run more than once: every table, index and column is guarded with
-- "if not exists", and each policy is dropped before it is created (the
-- migrations themselves do not do that, because a migration only ever runs once).
--
-- After this, set three variables in Vercel -> Settings -> Environment Variables:
--   NEXT_PUBLIC_SUPABASE_URL        Project Settings -> Data API -> Project URL
--   NEXT_PUBLIC_SUPABASE_ANON_KEY   the anon / public key
--   SUPABASE_SERVICE_ROLE_KEY       the service_role key (server only, never
--                                   in a NEXT_PUBLIC_ variable)
-- then redeploy. See START_HERE_SUPABASE.md for the auth and redirect settings.

`;

const RULE = "-- ───────────────────────────────────────────────────────────\n";
const POLICY = /^(create\s+policy\s+("?[A-Za-z0-9_]+"?)\s+on\s+([A-Za-z0-9_."]+))/gim;

const files = readdirSync(MIGRATIONS)
  .filter((name) => name.endsWith(".sql"))
  .sort();

let out = HEADER;
for (const name of files) {
  const body = readFileSync(path.join(MIGRATIONS, name), "utf8").trimEnd() + "\n";
  const guarded = body.replace(
    POLICY,
    (_all, statement, policy, table) =>
      `drop policy if exists ${policy} on ${table};\n${statement}`,
  );
  out += `${RULE}-- ${name}\n${RULE}${guarded}\n`;
}

writeFileSync(OUT, out);
console.log(`${OUT}: ${out.split("\n").length} lines from ${files.length} migrations`);
